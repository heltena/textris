#!/usr/bin/env python3
"""Prepare the recovered Turbo C sources for the WebAssembly build.

Nothing in ../src is modified. Copies of the .c/.h files are written to the
output directory with:

  * lower-case file names (the code says #include "gral.h", the files are Gral.h);
  * every non-ASCII character inside a string or character literal replaced by
    the octal escape of its DOS (CP437) byte, so '█' becomes '\\333' and the
    screens are drawn with the same bytes the DOS program wrote to video memory.
    Comments are left alone.

It also writes unity.c, a single translation unit that pulls in the platform
layer and then every game source file.

usage: prep.py <src_dir> <port_dir> <out_dir>
"""
import sys
from pathlib import Path

# Order matters only in that Textris.c (main) goes last.
C_FILES = ["Aleatori.c", "Gral.c", "Video.c", "Matriu.c", "Peces.c", "Musica.c",
           "Jugador.c", "Present.c", "Tecles.c", "Int_8.c", "Int_9.c", "Joc.c",
           "Textris.c"]
# Interfaces of the assembly modules: made visible to every file, because some
# of the original .c files call these routines without including the header
# (Turbo C accepted the implicit declaration; WebAssembly needs the exact type).
ASM_HEADERS = ["Acces.h", "Altaveu.h", "Convtips.h", "Interrup.h", "Pantalla.h",
               "Strobe.h", "Teclat.h"]


def convert(name, text):
    out = []
    state = "code"  # code | comment | string | char
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        two = text[i:i + 2]
        if state == "code":
            if ch == "#" and text[i:i + 6] == "#error":
                # free text up to the end of the line (accents, apostrophes...)
                end = text.find("\n", i)
                end = n if end < 0 else end
                out.append(text[i:end].encode("ascii", "replace").decode("ascii"))
                i = end
                continue
            if two == "/*":
                state = "comment"
                out.append(two)
                i += 2
                continue
            if ch == '"':
                state = "string"
            elif ch == "'":
                state = "char"
            elif ord(ch) > 126:
                sys.exit(f"{name}: non-ASCII character {ch!r} outside a literal or comment")
            out.append(ch)
        elif state == "comment":
            if two == "*/":
                state = "code"
                out.append(two)
                i += 2
                continue
            out.append(ch)
        else:
            quote = '"' if state == "string" else "'"
            if ch == "\\":
                out.append(two)
                i += 2
                continue
            if ch == quote:
                state = "code"
                out.append(ch)
            elif ord(ch) > 126:
                try:
                    byte = ch.encode("cp437")[0]
                except UnicodeEncodeError:
                    sys.exit(f"{name}: {ch!r} in a literal has no CP437 byte")
                out.append("\\%03o" % byte)
            else:
                out.append(ch)
        i += 1
    if state != "code":
        sys.exit(f"{name}: unterminated {state}")
    return "".join(out)


def main():
    src, port, out = (Path(p).resolve() for p in sys.argv[1:4])
    gen = out / "gen"
    gen.mkdir(parents=True, exist_ok=True)
    count = 0
    for f in sorted(src.iterdir()):
        if f.suffix.lower() in (".c", ".h"):
            (gen / f.name.lower()).write_text(convert(f.name, f.read_text(encoding="utf-8")),
                                              encoding="utf-8")
            count += 1
    missing = [f for f in C_FILES + ASM_HEADERS if not (gen / f.lower()).exists()]
    if missing:
        sys.exit("missing source files: " + ", ".join(missing))
    extra = sorted(f.name for f in src.iterdir()
                   if f.suffix.lower() == ".c" and f.name not in C_FILES)
    if extra:
        sys.exit("C files not listed in prep.py: " + ", ".join(extra))

    lines = ["/* Generated by tools/prep.py - do not edit. */",
             f'#include "{port / "platform.c"}"',
             f'#include "{port / "compat.h"}"']
    lines += [f'#include "gen/{h.lower()}"' for h in ASM_HEADERS]
    lines += [f'#include "gen/{c.lower()}"' for c in C_FILES]
    (out / "unity.c").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"prep: {count} files -> {gen}")


if __name__ == "__main__":
    main()
